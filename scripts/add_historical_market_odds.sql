create table if not exists public.historical_market_odds (
  id bigint generated by default as identity primary key,
  season text not null,
  competition text not null default 'Premier League',
  source text not null default 'football-data.co.uk',
  source_match_date date not null,
  source_kickoff_time time null,
  source_home_team text not null,
  source_away_team text not null,
  match_id text null references public.matches(match_id) on update cascade on delete set null,
  open_home_avg numeric null,
  open_draw_avg numeric null,
  open_away_avg numeric null,
  open_home_max numeric null,
  open_draw_max numeric null,
  open_away_max numeric null,
  close_home_avg numeric null,
  close_draw_avg numeric null,
  close_away_avg numeric null,
  close_home_max numeric null,
  close_draw_max numeric null,
  close_away_max numeric null,
  open_over25_avg numeric null,
  open_under25_avg numeric null,
  close_over25_avg numeric null,
  close_under25_avg numeric null,
  raw_row jsonb null,
  source_url text null,
  imported_at timestamptz not null default now(),
  unique(season,source,source_match_date,source_home_team,source_away_team)
);
create index if not exists historical_market_odds_match_id_idx on public.historical_market_odds(match_id);
create index if not exists historical_market_odds_season_date_idx on public.historical_market_odds(season,source_match_date);
alter table public.historical_market_odds enable row level security;
drop policy if exists historical_market_odds_read on public.historical_market_odds;
create policy historical_market_odds_read on public.historical_market_odds for select to anon, authenticated using (true);
grant select on public.historical_market_odds to anon, authenticated;
